"""DroneDrill AI - Scoring Engine.

Calculates multi-dimensional performance metrics for simulation sessions:
- Detection (Signal Detection Theory: d', criterion c, loglinear correction)
- Classification (Accuracy and confusion matrix)
- Decision (Response appropriateness via instructor decision tree rules)
- Timeliness (Reaction time against scenario duration and difficulty)
- Calibration (Brier score, confidence alignment)
- Skill-wise mapped cell outputs
"""

from pathlib import Path
import json
from typing import Any, Dict, List, Optional
import numpy as np
import scipy.stats as stats

from app.factors import CLASS_MIX

BASE_DIR = Path(__file__).resolve().parent.parent
DEFAULT_DECISION_TREE_PATH = BASE_DIR / "data" / "decision_tree.json"

# --- Editable Component Weights (Sum = 1.0) ---
WEIGHTS: Dict[str, float] = {
    "detection": 0.30,
    "classification": 0.25,
    "decision": 0.25,
    "timeliness": 0.10,
    "calibration": 0.10,
}


def load_decision_tree(file_path: Optional[Path] = None) -> Dict[str, Any]:
    """Load the instructor-editable decision tree JSON."""
    path = Path(file_path) if file_path else DEFAULT_DECISION_TREE_PATH
    if not path.exists():
        raise FileNotFoundError(f"Decision tree file not found at {path}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def score_session(
    scenario: Dict[str, Any],
    events: List[Dict[str, Any]],
    false_alarms: int = 0,
    decision_tree_path: Optional[Path] = None,
) -> Dict[str, Any]:
    """Evaluate trainee performance across detection, classification, decision, timeliness, and calibration.
    
    Parameters:
        scenario: The full scenario dictionary generated by DroneDrill AI.
        events: List of event dicts for objects encountered.
                Expected per object: {object_id, detected, detect_time_s, classified_as,
                                      threat_level_rated, response_chosen, confidence}
        false_alarms: Count of false alarms reported during the scenario.
        decision_tree_path: Optional path to override default decision tree.
    """
    objects = scenario.get("objects", [])
    n_obj = len(objects)
    noise_windows = scenario.get("noise_windows", 3)
    duration_s = scenario.get("duration_s", 60.0)
    difficulty_index = scenario.get("difficulty_index", 0.5)
    cell = scenario.get("cell", [])
    cell_str = "/".join(cell) if isinstance(cell, (list, tuple)) else str(cell)

    # Index scenario objects by id
    scenario_obj_map = {obj["id"]: obj for obj in objects}

    # Extract object-specific events (first or best event per object)
    event_by_id: Dict[str, Dict[str, Any]] = {}
    for ev in events:
        obj_id = ev.get("object_id")
        if obj_id and obj_id not in event_by_id:
            event_by_id[obj_id] = ev

    # --- 1. DETECTION (Signal Detection Theory) ---
    hits = 0
    missed_list: List[str] = []
    detected_events: List[Dict[str, Any]] = []

    for obj in objects:
        oid = obj["id"]
        ev = event_by_id.get(oid)
        if ev and ev.get("detected", False):
            hits += 1
            detected_events.append((obj, ev))
        else:
            missed_list.append(oid)

    misses = max(0, n_obj - hits)
    fa_raw = int(false_alarms)
    nw = scenario.get("noise_windows", 3)
    noise_windows = 3 if nw is None else int(nw)
    max_noise = max(0, noise_windows)
    fa_scored = int(np.clip(fa_raw, 0, max_noise))

    max_obj = max(0, n_obj)
    hits_scored = int(np.clip(hits, 0, max_obj))

    # Loglinear correction with clamping to avoid infinite z-scores
    hit_rate = (hits_scored + 0.5) / (max_obj + 1)
    fa_rate = (fa_scored + 0.5) / (max_noise + 1)

    # Clip hit_rate and fa_rate to [0.01, 0.99] before norm.ppf
    hit_rate = float(np.clip(hit_rate, 0.01, 0.99))
    fa_rate = float(np.clip(fa_rate, 0.01, 0.99))

    z_hit = float(stats.norm.ppf(hit_rate))
    z_fa = float(stats.norm.ppf(fa_rate))
    d_prime = float(z_hit - z_fa)
    criterion_c = float(-0.5 * (z_hit + z_fa))

    # Guard: if d_prime or criterion is not finite, set d_prime = 0 and detection_score = 0
    if not np.isfinite(d_prime) or not np.isfinite(criterion_c):
        d_prime = 0.0
        criterion_c = 0.0
        detection_score = 0.0
    else:
        # Normalized detection score clipped to [0, 1]
        detection_score = float(np.clip(d_prime / 3.0, 0.0, 1.0))
        if not np.isfinite(detection_score):
            detection_score = 0.0

    # --- 2. CLASSIFICATION ---
    # Confusion matrix initialization
    confusion_matrix = {tc: {pc: 0 for pc in CLASS_MIX} for tc in CLASS_MIX}

    correct_class_count = 0
    for obj, ev in detected_events:
        true_cls = obj.get("true_class", "unknown")
        pred_cls = ev.get("classified_as", "unknown")

        if true_cls in confusion_matrix and pred_cls in confusion_matrix[true_cls]:
            confusion_matrix[true_cls][pred_cls] += 1

        if true_cls == pred_cls:
            correct_class_count += 1

    if detected_events:
        classification_score = float(correct_class_count / len(detected_events))
    else:
        classification_score = 0.0

    # --- 3. DECISION (Instructor Rule Lookup) ---
    tree_data = load_decision_tree(decision_tree_path)
    rules = tree_data.get("rules", {})

    decision_scores: List[float] = []
    for obj, ev in detected_events:
        true_cls = obj.get("true_class", "unknown")
        behaviour = obj.get("behaviour_label", "benign")
        rule_key = f"{true_cls}|{behaviour}"

        rule = rules.get(rule_key, {})
        expected_level = rule.get("expected_threat_level", 1)
        response_weights = rule.get("responses", {})

        resp_chosen = ev.get("response_chosen", "")
        base_resp_score = float(response_weights.get(resp_chosen, 0.0))

        # 0.25 penalty if threat level rated does not match expected level
        rated_level = ev.get("threat_level_rated")
        if rated_level is not None and rated_level != expected_level:
            obj_dec_score = max(0.0, base_resp_score - 0.25)
        else:
            obj_dec_score = base_resp_score

        decision_scores.append(obj_dec_score)

    if decision_scores:
        decision_score = float(np.mean(decision_scores))
    else:
        decision_score = 0.0

    # --- 4. TIMELINESS ---
    limit_time = 0.6 * duration_s * (1.0 + difficulty_index)
    timeliness_scores: List[float] = []

    for _, ev in detected_events:
        detect_time = float(ev.get("detect_time_s", limit_time))
        obj_timeliness = float(np.clip(1.0 - (detect_time / limit_time), 0.0, 1.0))
        timeliness_scores.append(obj_timeliness)

    if timeliness_scores:
        timeliness_score = float(np.mean(timeliness_scores))
    else:
        timeliness_score = 0.0

    # --- 5. CALIBRATION (Brier Score) ---
    squared_errors: List[float] = []
    confidences: List[float] = []

    for obj, ev in detected_events:
        conf = float(ev.get("confidence", 0.5))
        confidences.append(conf)
        true_cls = obj.get("true_class", "unknown")
        pred_cls = ev.get("classified_as", "unknown")
        is_correct = 1.0 if true_cls == pred_cls else 0.0

        sq_err = (conf - is_correct) ** 2
        squared_errors.append(sq_err)

    if detected_events:
        brier = float(np.mean(squared_errors))
        calibration_score = float(np.clip(1.0 - brier, 0.0, 1.0))
        mean_confidence = float(np.mean(confidences))
        mean_accuracy = classification_score
    else:
        brier = 0.0
        calibration_score = 0.0
        mean_confidence = 0.0
        mean_accuracy = 0.0

    # --- OVERALL WEIGHTED SCORE ---
    overall = (
        WEIGHTS["detection"] * detection_score
        + WEIGHTS["classification"] * classification_score
        + WEIGHTS["decision"] * decision_score
        + WEIGHTS["timeliness"] * timeliness_score
        + WEIGHTS["calibration"] * calibration_score
    )
    overall_score = float(np.clip(overall, 0.0, 1.0))

    # --- SKILL-WISE OUTPUT (for skill model mapping) ---
    skill_scores = {
        f"detection|{cell_str}": round(detection_score, 4),
        f"classification|{cell_str}": round(classification_score, 4),
        f"decision|{cell_str}": round(decision_score, 4),
        f"timeliness|{cell_str}": round(timeliness_score, 4),
        f"calibration|{cell_str}": round(calibration_score, 4),
        f"overall|{cell_str}": round(overall_score, 4),
    }

    return {
        "overall": round(overall_score, 4),
        "overall_score": round(overall_score, 4),
        "detection_score": round(detection_score, 4),
        "classification_score": round(classification_score, 4),
        "decision_score": round(decision_score, 4),
        "timeliness_score": round(timeliness_score, 4),
        "calibration_score": round(calibration_score, 4),
        "detection": {
            "score": round(detection_score, 4),
            "hits": hits,
            "misses": misses,
            "false_alarms": fa_raw,
            "false_alarms_raw": fa_raw,
            "false_alarms_scored": fa_scored,
            "n_objects": n_obj,
            "noise_windows": noise_windows,
            "hit_rate": round(hit_rate, 4),
            "fa_rate": round(fa_rate, 4),
            "d_prime": round(d_prime, 4),
            "criterion_c": round(criterion_c, 4),
            "criterion": round(criterion_c, 4),
        },
        "classification": {
            "score": round(classification_score, 4),
            "accuracy": round(classification_score, 4),
            "confusion_matrix": confusion_matrix,
        },
        "decision": {
            "score": round(decision_score, 4),
        },
        "timeliness": {
            "score": round(timeliness_score, 4),
            "limit_s": round(limit_time, 2),
        },
        "calibration": {
            "score": round(calibration_score, 4),
            "brier_score": round(brier, 4),
            "mean_confidence": round(mean_confidence, 4),
            "mean_accuracy": round(mean_accuracy, 4),
        },
        "confusion_matrix": confusion_matrix,
        "missed": missed_list,
        "missed_objects": missed_list,
        "false_alarms": fa_raw,
        "false_alarms_raw": fa_raw,
        "false_alarms_scored": fa_scored,
        "skill_scores": skill_scores,
    }
